"""COSMOS's wavetables, generated at build time (fm1.toml gen): the moon's four characters and a sine, a cycle
of 1024 int16 each, into a header.
  tools/gen_waves.py --out GEN_DIR        writes GEN_DIR/waves.h
The characters, as harmonic spectra (sine terms), the same as the browser sketch's (web/emulator):
  NEW     pure and dark: the fundamental, a trace of the second
  WAXING  soft, rounded: odd harmonics falling as 1/n^2, a little of the even ones
  FULL    rich: every harmonic at 1/n
  WANING  metallic: the fundamental and a sparse cluster high up (7, 9, 11, 13, 17, 19, 23)
24 harmonics at most: the drones sit low (A2 is 110 Hz), so the top one stays under Nyquist up to about 900 Hz."""
import math
import sys
from pathlib import Path

N, NH = 1024, 24
WORLDS = [
    ("NEW", lambda n: 1.0 if n == 1 else 0.04 if n == 2 else 0.0),
    ("WAXING", lambda n: (1.0 if n == 1 else 1.6 / (n * n)) if n % 2 else 0.15 / (n * n)),
    ("FULL", lambda n: 1.0 / n),
    ("WANING", lambda n: 0.8 if n == 1 else 0.55 / math.sqrt(n / 7) if n in (7, 9, 11, 13, 17, 19, 23) else 0.0),
]


def table(amp):
    s = [sum(amp(n) * math.sin(2 * math.pi * n * i / N) for n in range(1, NH + 1)) for i in range(N)]
    peak = max(abs(v) for v in s)
    return [round(v / peak * 29000) for v in s]


def c_array(vals):
    return ",\n".join("    " + ", ".join(f"{v:6d}" for v in vals[i:i + 12]) for i in range(0, len(vals), 12))


def main():
    out = Path(sys.argv[sys.argv.index("--out") + 1])
    out.mkdir(parents=True, exist_ok=True)
    parts = ["/* generated by tools/gen_waves.py: the moon's four characters and a sine, 1024 int16 a cycle */",
             "#pragma once", "#include <stdint.h>", f"#define WAVE_N {N}u", "#define WAVE_BITS 10u", ""]
    parts.append("static const int16_t WAVES[4][WAVE_N] = {")
    for name, amp in WORLDS:
        parts.append(f"  {{ /* {name} */\n{c_array(table(amp))}\n  }},")
    parts.append("};")
    parts.append("static const int16_t SINE[WAVE_N] = {")
    parts.append(c_array([round(29000 * math.sin(2 * math.pi * i / N)) for i in range(N)]))
    parts.append("};")
    (out / "waves.h").write_text("\n".join(parts) + "\n")
    print(f"waves: {len(WORLDS)} characters and a sine, {(len(WORLDS) + 1) * N * 2} B")


if __name__ == "__main__":
    main()
