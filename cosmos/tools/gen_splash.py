"""COSMOS's splash, generated at build time (fm1.toml gen): where the stars gather, the word COSMOS.
  tools/gen_splash.py --out GEN_DIR      writes GEN_DIR/splash_data.h
The word is set in Michroma (third_party/fonts/michroma, SIL OFL 1.1), 212 pixels wide, centred on the 240-pixel
screen, and a star sits on every other pixel of it (a 2-pixel grid: dotted, not solid), as tools/splash_preview.py
draws it. Needs Pillow."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT = Path(__file__).resolve().parents[2] / "third_party" / "fonts" / "michroma" / "Michroma-Regular.ttf"
W, WIDE, WORD = 240, 212, "COSMOS"


def main():
    out = Path(sys.argv[sys.argv.index("--out") + 1])
    out.mkdir(parents=True, exist_ok=True)
    f = ImageFont.truetype(str(FONT), 44)
    m = Image.new("L", (W * 2, 120), 0)
    ImageDraw.Draw(m).text((0, 10), WORD, font=f, fill=255)
    m = m.crop(m.getbbox())
    m = m.resize((WIDE, max(1, round(m.height * WIDE / m.width))), Image.LANCZOS)
    ox, oy, mp = (W - m.width) // 2, (W - m.height) // 2, m.load()
    pts = [(ox + x, oy + y) for y in range(0, m.height, 2) for x in range(0, m.width, 2) if mp[x, y] > 128]
    p = ["/* generated by tools/gen_splash.py: the word COSMOS in Michroma (SIL OFL 1.1), a star every other pixel */",
         "#pragma once", "#include <stdint.h>", "",
         f"#define NSPLASH {len(pts)}u", "static const uint8_t SPLASH_XY[NSPLASH][2] = {"]
    for i in range(0, len(pts), 8):
        p.append("    " + " ".join(f"{{{x}, {y}}}," for x, y in pts[i:i + 8]))
    p.append("};")
    (out / "splash_data.h").write_text("\n".join(p) + "\n")
    print(f"splash: {len(pts)} stars in the word ({len(pts) * 2} B)")


if __name__ == "__main__":
    main()
