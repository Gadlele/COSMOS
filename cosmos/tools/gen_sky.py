"""COSMOS's sky data, generated at build time (fm1.toml gen): the stars (data/stars.csv) and the cities
(data/cities.csv), into a header.
  tools/gen_sky.py --out GEN_DIR        writes GEN_DIR/sky_data.h
A star is 5 bytes: right ascension as 0..65535 for 0..360 degrees, declination in hundredths of a degree, the
magnitude in tenths. A city is its name, its latitude and longitude in hundredths, its standard offset in quarter
hours and its summer-time rule."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
RULES = {"-": 0, "EU": 1, "US": 2, "AU": 3, "NZ": 4}   # dsp/astro.h DST_*


def rows(path):
    return [line.strip().split(",") for line in path.read_text().splitlines() if line.strip() and line[0] != "#"]


def main():
    out = Path(sys.argv[sys.argv.index("--out") + 1])
    out.mkdir(parents=True, exist_ok=True)
    stars = rows(HERE / "data" / "stars.csv")
    cities = rows(HERE / "data" / "cities.csv")
    p = ["/* generated by tools/gen_sky.py from data/stars.csv and data/cities.csv */", "#pragma once",
         "#include <stdint.h>", "",
         "typedef struct { uint16_t ra; int16_t dec; int8_t mag10; } star_t;   /* see tools/gen_sky.py */",
         f"#define NSTARS {len(stars)}u", "static const star_t STARS[NSTARS] = {"]
    for hr, ra, dec, mag in stars:
        p.append(f"    {{{round(float(ra) / 360 * 65536) & 0xFFFF}u, {round(float(dec) * 100)}, {round(float(mag) * 10)}}},")
    p += ["};", "",
          "typedef struct { char name[14]; int16_t lat100, lon100; int8_t utc4; uint8_t dst; } city_t;",
          f"#define NCITIES {len(cities)}u", "static const city_t CITIES[NCITIES] = {"]
    for name, lat, lon, utc, dst in cities:
        assert len(name) <= 13, name
        p.append(f'    {{"{name}", {round(float(lat) * 100)}, {round(float(lon) * 100)}, {round(float(utc) * 4)}, '
                 f"{RULES[dst]}}},")
    p.append("};")
    (out / "sky_data.h").write_text("\n".join(p) + "\n")
    print(f"sky: {len(stars)} stars ({len(stars) * 5} B), {len(cities)} cities")


if __name__ == "__main__":
    main()
