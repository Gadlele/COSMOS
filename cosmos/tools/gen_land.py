"""VOYAGE's map, generated at build time (fm1.toml gen): the land's outline (data/land.txt, tools/land_from_ne.py),
into a header.
  tools/gen_land.py --out GEN_DIR        writes GEN_DIR/land_data.h
LAND holds the rings one after another: each its number of steps (2 bytes), its first point (x, y: 2 bytes each, in
0.2 degrees from 180 W and from 90 S), then each step as two signed bytes (dx, dy); a step longer than 127 is split.
The last point joins the first."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]


def main():
    out = Path(sys.argv[sys.argv.index("--out") + 1])
    out.mkdir(parents=True, exist_ok=True)
    data, rings = bytearray(), 0
    for line in (HERE / "data" / "land.txt").read_text().splitlines():
        if not line.strip() or line[0] == "#":
            continue
        v = [int(t) for t in line.split()]
        pts = list(zip(v[0::2], v[1::2]))
        steps, (px, py) = bytearray(), pts[0]
        n = 0
        for x, y in pts[1:]:
            dx, dy = x - px, y - py
            while dx or dy:
                sx, sy = max(-127, min(127, dx)), max(-127, min(127, dy))
                steps += bytes([sx & 255, sy & 255])
                dx, dy, n = dx - sx, dy - sy, n + 1
            px, py = x, y
        data += n.to_bytes(2, "little") + pts[0][0].to_bytes(2, "little") + pts[0][1].to_bytes(2, "little") + steps
        rings += 1
    p = ["/* generated by tools/gen_land.py from data/land.txt (Natural Earth 1:110m land, public domain) */",
         "#pragma once", "#include <stdint.h>", "", f"#define NLAND_RINGS {rings}u", f"#define LAND_BYTES {len(data)}u",
         "static const uint8_t LAND[LAND_BYTES] = {"]
    for i in range(0, len(data), 24):
        p.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    p.append("};")
    (out / "land_data.h").write_text("\n".join(p) + "\n")
    print(f"land: {rings} rings ({len(data)} B)")


if __name__ == "__main__":
    main()
